-- CR/LF di DEPT_FIELD_01 dibuang. Pemakaian: @spool_dept.sql   (menulis FM_DEPARTMENT.psv)
SET TERMOUT OFF FEEDBACK OFF VERIFY OFF PAGESIZE 0 LINESIZE 32767 TRIMSPOOL ON
SET MARKUP CSV ON DELIMITER '|' QUOTE OFF
SET HEADING ON
SPOOL FM_DEPARTMENT.psv
SELECT DEPT_COMP_CODE, DEPT_DIVN_CODE, DEPT_CODE,
       REPLACE(REPLACE(DEPT_FIELD_01,CHR(13),' '),CHR(10),' ') AS DEPT_FIELD_01
  FROM FM_DEPARTMENT;
SPOOL OFF
SET MARKUP CSV OFF
